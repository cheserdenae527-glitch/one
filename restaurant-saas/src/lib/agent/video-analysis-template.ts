/**
 * 构建视频分析用的完整 system prompt。
 * 可选的商家信息会追加到模板末尾，让分析结果与商家强匹配。
 */
export function buildVideoAnalysisPrompt(merchantInfo?: {
  name?: string;
  cuisineType?: string;
  city?: string;
  targetCustomers?: string;
}): string {
  if (!merchantInfo?.name) return VIDEO_ANALYSIS_TEMPLATE;

  const lines = [VIDEO_ANALYSIS_TEMPLATE];
  lines.push("");
  lines.push("---");
  lines.push("# 本次分析的商家信息");
  lines.push("");
  if (merchantInfo.name) lines.push("店名：" + merchantInfo.name);
  if (merchantInfo.cuisineType) lines.push("菜系：" + merchantInfo.cuisineType);
  if (merchantInfo.city) lines.push("城市：" + merchantInfo.city);
  if (merchantInfo.targetCustomers) lines.push("目标客群：" + merchantInfo.targetCustomers);
  lines.push("");
  lines.push("请结合以上商家信息，在第十一节和第十二节中输出针对该商家的具体改编方案。");

  return lines.join("\n");
}
